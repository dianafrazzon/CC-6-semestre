    private void btn_gerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_gerarActionPerformed

        try {
            IGerarLink c = (IGerarLink) Naming.lookup("rmi://localhost/GerarLink");
            String txt = txt_link.getText();
            String temp = c.gerarLink(txt);
            if (temp.equals("CADASTRADO")) {
                JOptionPane.showMessageDialog(this, "Link com encurtador já gerado!");
            } else {
                jTextAreaLinkEncurtado.setText(temp);
            }
        } catch (Exception e) {
            System.out.println("Error: " + e);
        }
    }//GEN-LAST:event_btn_gerarActionPerformed

